"""Generate JSON Schema 2020-12 and T-SQL DDL from a stored contract record."""

import re

from datacontracts import owner_system

OPEN_KINDS = {"endpoint", "event", "soap"}
SQL_KINDS = {"table", "view"}


def slugify(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-") or "contract"


def filename(contract: dict, ext: str) -> str:
    return f"{contract['code']}-{slugify(contract['name'])}.{ext}"


def _json_type(src: str) -> dict:
    t = src.lower().strip()
    m = re.match(r"n?(var)?char\((\d+)\)", t)
    if m:
        return {"type": "string", "maxLength": int(m.group(2))}
    m = re.match(r"string\((\d+)\)", t)
    if m:
        return {"type": "string", "maxLength": int(m.group(1))}
    if t.startswith("uniqueidentifier") or t == "uuid":
        return {"type": "string", "format": "uuid"}
    if t.startswith("decimal") or t in {"money", "float", "real"}:
        return {"type": "number"}
    if t.startswith(("int", "bigint", "smallint", "tinyint")):
        return {"type": "integer"}
    if t == "bit" or t == "bool" or t == "boolean":
        return {"type": "boolean"}
    if t == "yyyymmdd":
        return {"type": "string", "pattern": r"^\d{8}$"}
    if t == "date":
        return {"type": "string", "format": "date"}
    if t in {"datetime", "datetime2", "datetimeoffset"}:
        return {"type": "string", "format": "date-time"}
    if t == "rowversion":
        return {"type": "string", "contentEncoding": "base64"}
    if t.startswith("array"):
        return {"type": "array"}
    return {"type": "string"}


def to_json_schema(c: dict) -> dict:
    props = {}
    for f in c.get("fields", []):
        p = _json_type(f["type"])
        if f.get("notes"):
            p["description"] = f["notes"]
        p["x-sourceType"] = f["type"]
        props[f["name"]] = p
    return {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$id": f"https://devatlas.internal/contracts/{filename(c, 'schema.json')}",
        "title": f"{c['code']} {c['name']}",
        "description": c.get("summary", ""),
        "type": "object",
        "properties": props,
        "required": [f["name"] for f in c.get("fields", []) if f.get("required")],
        "additionalProperties": c["kind"] in OPEN_KINDS,
        "x-devatlas": {
            "code": c["code"], "kind": c["kind"], "status": c["status"], "version": c["version"],
            "owner": c["owner"], "owner_system": owner_system(c), "direction": c["direction"],
            "producers": c.get("producers", []), "consumers": c.get("consumers", []), "rules": c.get("rules", []),
        },
    }


def _ident(name: str) -> str:
    base = name.split(".")[-1]
    ident = re.sub(r"[^A-Za-z0-9_]+", "_", base).strip("_")
    return ident if ident and not ident[0].isdigit() else f"T_{ident}"


def _sql_type(src: str) -> tuple[str, bool]:
    """(sql type, is identity)"""
    t = src.strip()
    if t.lower() == "int identity":
        return "int IDENTITY(1,1)", True
    if t.lower() == "yyyymmdd":
        return "char(8)", False
    if t.lower().startswith("string"):
        m = re.match(r"string\((\d+)\)", t.lower())
        return (f"nvarchar({m.group(1)})" if m else "nvarchar(max)"), False
    if t.lower() == "uuid":
        return "uniqueidentifier", False
    if t.lower() in {"datetime"}:
        return "datetime2", False
    return t, False


def to_sql(c: dict) -> str:
    if c["kind"] not in SQL_KINDS:
        raise ValueError(f"SQL DDL is only available for tables and views, not {c['kind']}.")
    table = _ident(c["name"])
    pk = next((f["name"] for f in c.get("fields", []) if f.get("required") and f["name"].lower().endswith("id")), None)
    lines = [
        f"-- {c['code']} {c['name']} v{c['version']} ({c['status']})",
        f"-- Owner: {c['owner']}. Generated by DevAtlas from the contract registry.",
        f"-- DROP TABLE IF EXISTS dbo.{table};",
        f"CREATE TABLE dbo.{table} (",
    ]
    cols = []
    for f in c.get("fields", []):
        sql_type, _ = _sql_type(f["type"])
        if sql_type.lower() == "rowversion":
            col = f"    [{f['name']}] rowversion"
        else:
            col = f"    [{f['name']}] {sql_type} {'NOT NULL' if f.get('required') else 'NULL'}"
        if f["name"] == pk:
            col += " PRIMARY KEY"
        if f.get("notes"):
            col += f"  -- {f['notes']}"
        cols.append(col)
    # place commas before comments
    out = []
    for i, col in enumerate(cols):
        sep = "," if i < len(cols) - 1 else ""
        if "  -- " in col:
            body, comment = col.split("  -- ", 1)
            out.append(f"{body}{sep}  -- {comment}")
        else:
            out.append(f"{col}{sep}")
    lines += out
    lines.append(");")
    if c.get("rules"):
        lines.append("")
        lines.append("-- Compatibility rules:")
        lines += [f"--   {r}" for r in c["rules"]]
    return "\n".join(lines) + "\n"
